"""LLM-as-judge evaluation of the "visual-textual consistency" between the forecast and the
generated reasoning text (multimodal; distinct from the pure-text shape judge in
text_alignment_eval.py).

For each generated forecast, plot history + forecast, also give the forecast values as text, and hand
both together with the model's own generated reasoning to the judge LLM, asking "does the forecast
(plot + numbers) match the trend described by the reasoning text", scored 1-5 (supportiveness on the
forecasting side).

Data source: a same-named npz+jsonl pair produced by infer_forecast.py
(``forecast_preds.npz`` / ``forecast_preds.jsonl``, same directory and row order) + parquet (for
``history_values``/``history_timestamps``, aligned by id; ids are unique within the test split, see
text_alignment_eval.load_roi_reference).

The plot shows **only history + the model's own forecast** (no ground truth) -- what is judged is
"does the forecast match the text", not "does the forecast match the truth" (that is what CRPS/PCC
are for); mixing in the ground-truth curve would let the judge LLM overstep and use truth information
to bias the consistency judgement.

Reuses the judge infrastructure of text_alignment_eval (client construction / retries / response
parsing / domain mapping / resumable checkpoint mode) instead of reinventing it; only the image
rendering and this module's own judge prompt are new.
"""
import argparse
import base64
import concurrent.futures
import csv
import io
import json
import os

import numpy as np
import pandas as pd

from chronos_llm.eval.metrics import _median_index
from chronos_llm.eval.text_alignment_eval import (
    DEFAULT_API_BASE_URL,
    DEFAULT_JUDGE_MODEL,
    _load_api_key,
    _retry_exceptions,
    _with_retry,
    dataset_name_of,
    domain_of,
    group_records_by_domain,
    parse_judge_response,
)

VISUAL_JUDGE_SYSTEM = (
    "You are a careful evaluator checking whether a numeric time-series forecast (shown as a "
    "plot AND as exact numbers) is CONSISTENT with a separate piece of reasoning text that was "
    "supposed to describe/justify that same forecast. You are NOT checking whether the forecast "
    "is accurate against any ground truth -- there is no ground truth here. You are ONLY checking "
    "whether the forecast (what the model actually predicted) matches what the reasoning text "
    "says it predicted: direction of change, magnitude/level qualifiers, shape (peaks, troughs, "
    "turning points, smoothness), and any claims specific to the highlighted ROI region."
)

VISUAL_JUDGE_USER_TEMPLATE = """[Reasoning text generated by the model]
{gen_text}

[The forecast the model actually produced]
The plot below shows recent history (gray) followed by the model's own predicted forecast \
(blue dashed = median, shaded band = 10-90% interval). The shaded yellow region is the ROI \
(region of interest) that the reasoning text specifically discusses.

Exact predicted median values for the forecast window (rounded, chronological order): {values_str}
ROI covers steps [{roi_start}, {roi_end}) within this window; predicted median values there: {roi_values_str}

Rate how CONSISTENT the actual forecast (plot + numbers above) is with what the reasoning text \
describes, on this 1-5 scale:
5 = fully consistent -- direction, magnitude, and shape all match the text
4 = mostly consistent -- minor nuance mismatch but same overall story
3 = partially consistent -- right broad direction but a clearly wrong detail (e.g. wrong shape, \
or magnitude claim not supported by the numbers)
2 = mostly inconsistent -- forecast contradicts a central claim of the text
1 = contradictory -- forecast is essentially the opposite of what the text describes

Respond with ONLY a JSON object of the form {{"score": <int 1-5>, "reason": "<one short sentence>"}}"""


def _q_index(levels, q):
    return int(np.argmin(np.abs(np.asarray(levels, float) - q)))


def render_forecast_png(history, hist_ts, future_ts, median, lo, hi, roi_mask, title="", hist_n=200):
    """History (gray) + predicted median (blue dashed) + 10-90% band (light blue) + ROI (yellow background), **no ground truth**. Returns PNG bytes."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    hist = np.asarray(history, float).ravel()
    hts = pd.to_datetime(np.asarray(hist_ts).ravel())
    hts = hts[-len(hist):] if len(hts) >= len(hist) else hts
    hist = hist[-len(hts):]
    if hist_n and len(hist) > hist_n:
        hist, hts = hist[-hist_n:], hts[-hist_n:]
    fts = pd.to_datetime(np.asarray(future_ts).ravel())[: len(median)]

    fig, ax = plt.subplots(figsize=(11, 4.5))
    ax.plot(hts, hist, color="#444", lw=1.3, label="History")
    if len(fts):
        ax.axvline(fts[0], color="#999", ls=":", lw=1)
    roi = np.asarray(roi_mask, bool)[: len(median)]
    roi_idx = np.where(roi)[0]
    if roi_idx.size:
        ax.axvspan(fts[roi_idx[0]], fts[min(roi_idx[-1], len(fts) - 1)],
                   color="#ffe9a8", alpha=0.55, label="ROI")
    ax.fill_between(fts, lo, hi, color="#1f77b4", alpha=0.16, label="Pred 10-90%")
    ax.plot(fts, median, color="#1f77b4", lw=1.9, ls="--", label="Predicted median")
    if title:
        ax.set_title(title, fontsize=10.5)
    ax.set_xlabel("timestamp"); ax.set_ylabel("value")
    ax.legend(loc="best", fontsize=8); ax.grid(alpha=0.25)
    fig.autofmt_xdate(); fig.tight_layout()
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=120)
    plt.close(fig)
    return buf.getvalue()


def build_visual_judge_messages(gen_text, median, roi_start, roi_end, png_bytes):
    med = np.asarray(median, float)
    roi_vals = med[roi_start:roi_end]
    values_str = "[" + ", ".join(f"{v:.4g}" for v in med) + "]"
    roi_values_str = "[" + ", ".join(f"{v:.4g}" for v in roi_vals) + "]"
    user_text = VISUAL_JUDGE_USER_TEMPLATE.format(
        gen_text=gen_text, values_str=values_str,
        roi_start=int(roi_start), roi_end=int(roi_end), roi_values_str=roi_values_str,
    )
    b64 = base64.b64encode(png_bytes).decode("ascii")
    return [
        {"role": "system", "content": VISUAL_JUDGE_SYSTEM},
        {"role": "user", "content": [
            {"type": "text", "text": user_text},
            {"type": "image_url", "image_url": {"url": f"data:image/png;base64,{b64}"}},
        ]},
    ]


def call_visual_judge(gen_text, median, roi_start, roi_end, png_bytes, client,
                       model=DEFAULT_JUDGE_MODEL, max_attempts=3, base_delay=1.0):
    messages = build_visual_judge_messages(gen_text, median, roi_start, roi_end, png_bytes)

    def _call():
        return client.chat.completions.create(model=model, messages=messages)

    resp = _with_retry(_call, max_attempts=max_attempts, base_delay=base_delay,
                        retry_exceptions=_retry_exceptions())
    raw = resp.choices[0].message.content
    score, reason = parse_judge_response(raw)
    return score, reason, raw


def build_openai_client(api_base_url=DEFAULT_API_BASE_URL, api_key=None):
    from openai import OpenAI
    return OpenAI(base_url=api_base_url, api_key=api_key or _load_api_key())


def load_records(npz_path, jsonl_path, parquet_path, split="test"):
    """Align npz (values) + jsonl (gen_text) + parquet (history) by id and produce a unified record list."""
    npz = np.load(npz_path, allow_pickle=True)
    with open(jsonl_path, encoding="utf-8") as f:
        jrows = [json.loads(l) for l in f if l.strip()]
    jsonl_by_id = {r["id"]: r for r in jrows}

    # The split filter is pushed down at read time via `filters` (not read everything and then filter
    # with df[...]): history_values/history_timestamps are variable-length nested array columns and the
    # train split is much larger in memory than the test split, so filtering after reading can run out
    # of memory on a small machine.
    cols = ["id", "dataset_name", "split", "history_values", "history_timestamps", "future_timestamps"]
    df = pd.read_parquet(parquet_path, columns=cols, filters=[("split", "=", split)])
    pq_by_id = {row["id"]: row for _, row in df.iterrows()}

    levels = npz["quantile_levels"].astype(float)
    med_i, lo_i, hi_i = _median_index(levels), _q_index(levels, 0.1), _q_index(levels, 0.9)

    # npz decompresses lazily: every ``npz["key"]`` re-decompresses a new array from disk (NpzFile does
    # not cache decompressed results); indexing repeatedly inside the loop would make each slice pin its
    # own full copy of pred_quantiles. Decompress once before the loop and slice the same array inside
    # it, so all samples share one buffer.
    ids_arr = npz["ids"]
    valid_mask_arr = npz["valid_mask"]
    roi_mask_arr = npz["roi_mask"]
    pred_quantiles_arr = npz["pred_quantiles"]
    dataset_names_arr = npz["dataset_names"] if "dataset_names" in npz.files else None

    records = []
    for i, sid in enumerate(ids_arr):
        sid = str(sid)
        if sid not in jsonl_by_id or sid not in pq_by_id:
            continue
        jr = jsonl_by_id[sid]
        prow = pq_by_id[sid]
        H = int(valid_mask_arr[i].sum())
        roi = roi_mask_arr[i][:H].astype(bool)
        roi_idx = np.where(roi)[0]
        roi_start, roi_end = (int(roi_idx[0]), int(roi_idx[-1]) + 1) if roi_idx.size else (0, 0)
        ds_name = str(dataset_names_arr[i]) if dataset_names_arr is not None else str(prow["dataset_name"])
        records.append({
            "id": sid, "row": i, "dataset_name": ds_name, "domain": domain_of(ds_name),
            "gen_text": jr.get("gen_text") or "",
            "history_values": prow["history_values"], "history_timestamps": prow["history_timestamps"],
            "future_timestamps": prow["future_timestamps"],
            "median": pred_quantiles_arr[i, med_i, :H],
            "lo": pred_quantiles_arr[i, lo_i, :H], "hi": pred_quantiles_arr[i, hi_i, :H],
            "roi_mask": roi, "roi_start": roi_start, "roi_end": roi_end,
        })
    return records


def run_visual_judge_batch(records, client, model=DEFAULT_JUDGE_MODEL, max_workers=3,
                            max_attempts=3, base_delay=1.0, progress_every=50,
                            checkpoint_path=None, hist_n=200):
    results = {}
    if checkpoint_path and os.path.exists(checkpoint_path):
        with open(checkpoint_path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                obj = json.loads(line)
                results[obj["id"]] = obj

    todo = [rec for rec in records if rec["id"] not in results]
    if not todo:
        return results

    ckpt_f = open(checkpoint_path, "a", encoding="utf-8") if checkpoint_path else None

    def _one(rec):
        try:
            png = render_forecast_png(
                rec["history_values"], rec["history_timestamps"], rec["future_timestamps"],
                rec["median"], rec["lo"], rec["hi"], rec["roi_mask"],
                title=f"{rec['id']}  ({rec['dataset_name']})", hist_n=hist_n,
            )
            score, reason, raw = call_visual_judge(
                rec["gen_text"], rec["median"], rec["roi_start"], rec["roi_end"], png,
                client, model=model, max_attempts=max_attempts, base_delay=base_delay,
            )
            return {"id": rec["id"], "score": score, "reason": reason, "raw": raw, "error": None}
        except Exception as e:  # noqa: BLE001 one failed record must not take down the batch
            return {"id": rec["id"], "score": None, "reason": "", "raw": "", "error": str(e)}

    done = 0
    try:
        with concurrent.futures.ThreadPoolExecutor(max_workers=max_workers) as ex:
            futures = [ex.submit(_one, rec) for rec in todo]
            for fut in concurrent.futures.as_completed(futures):
                out = fut.result()
                results[out["id"]] = out
                if ckpt_f:
                    ckpt_f.write(json.dumps(out, ensure_ascii=False) + "\n")
                    ckpt_f.flush()
                done += 1
                if progress_every and done % progress_every == 0:
                    print(f"  visual judge: {done}/{len(todo)} done")
    finally:
        if ckpt_f:
            ckpt_f.close()
    return results


def summarize(items):
    n = len(items)
    scores = [it["score"] for it in items if it.get("score") is not None]
    dist = {k: 0 for k in range(1, 6)}
    for s in scores:
        dist[s] = dist.get(s, 0) + 1
    return {
        "n": n, "n_scored": len(scores),
        "judge_fail_rate": (n - len(scores)) / n if n else float("nan"),
        "mean": float(np.mean(scores)) if scores else float("nan"),
        "std": float(np.std(scores)) if scores else float("nan"),
        "distribution": dist,
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--npz", required=True, help="forecast_preds.npz produced by infer_forecast.py")
    ap.add_argument("--jsonl", default=None, help="same-named jsonl; defaults to the .jsonl next to --npz")
    ap.add_argument("--parquet", required=True)
    ap.add_argument("--out_dir", required=True)
    ap.add_argument("--limit", type=int, default=0, help="judge only the first N records (0=all)")
    ap.add_argument("--hist_n", type=int, default=200, help="plot the most recent N history points")
    ap.add_argument("--judge_model", default=DEFAULT_JUDGE_MODEL)
    ap.add_argument("--api_base_url", default=DEFAULT_API_BASE_URL)
    ap.add_argument("--max_workers", type=int, default=3)
    args = ap.parse_args(argv)

    jsonl_path = args.jsonl or (args.npz[:-4] + ".jsonl" if args.npz.endswith(".npz") else args.npz + ".jsonl")
    os.makedirs(args.out_dir, exist_ok=True)

    records = load_records(args.npz, jsonl_path, args.parquet)
    print(f"loaded {len(records)} records (npz={args.npz}, jsonl={jsonl_path})")
    unknown = [r for r in records if r["domain"] is None]
    if unknown:
        print(f"warning: {len(unknown)} records have a dataset_name outside DOMAIN_SOURCES, grouped as 'Unknown': "
              f"{sorted(set(r['dataset_name'] for r in unknown))}")

    subset = records if args.limit <= 0 else records[: args.limit]
    client = build_openai_client(api_base_url=args.api_base_url)
    ckpt = os.path.join(args.out_dir, "visual_judge_raw.jsonl")
    print(f"calling {args.judge_model} for visual-textual consistency scores, n={len(subset)}, workers={args.max_workers}, checkpoint={ckpt}")
    judge_results = run_visual_judge_batch(
        subset, client, model=args.judge_model, max_workers=args.max_workers,
        checkpoint_path=ckpt, hist_n=args.hist_n,
    )

    items = [{"score": judge_results.get(r["id"], {}).get("score")} for r in subset]
    overall = summarize(items)
    dom_groups = group_records_by_domain(subset)
    by_domain = {dom: summarize([{"score": judge_results.get(r["id"], {}).get("score")} for r in recs])
                 for dom, recs in dom_groups.items()}

    print(f"\n{'scope':10} {'n':>4} {'n_scored':>9} | {'mean':>6} | {'std':>6} | {'judge_fail_rate':>15}")
    print("-" * 66)
    for scope, s in [("ALL", overall)] + sorted(by_domain.items()):
        print(f"{scope:10} {s['n']:>4} {s['n_scored']:>9} | {s['mean']:6.3f} | {s['std']:6.3f} | "
              f"{s['judge_fail_rate']:15.4f}")
    n_fail = sum(1 for v in judge_results.values() if v.get("error"))
    if n_fail:
        print(f"warning: {n_fail}/{len(judge_results)} judge calls failed after exhausting retries (score=None)")

    summary_csv = os.path.join(args.out_dir, "visual_judge_summary.csv")
    with open(summary_csv, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["scope", "n", "n_scored", "judge_fail_rate", "mean", "std",
                                           "dist_1", "dist_2", "dist_3", "dist_4", "dist_5"])
        w.writeheader()
        for scope, s in [("ALL", overall)] + sorted(by_domain.items()):
            row = {k: v for k, v in s.items() if k != "distribution"}
            row["scope"] = scope
            for k, v in s["distribution"].items():
                row[f"dist_{k}"] = v
            w.writerow(row)
    print(f"\nwrote {summary_csv}")

    per_sample_csv = os.path.join(args.out_dir, "per_sample.csv")
    with open(per_sample_csv, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["id", "dataset_name", "domain", "score", "reason"])
        w.writeheader()
        for r in subset:
            jr = judge_results.get(r["id"], {})
            w.writerow({"id": r["id"], "dataset_name": r["dataset_name"], "domain": r["domain"] or "Unknown",
                        "score": jr.get("score", ""), "reason": jr.get("reason", "")})
    print(f"wrote {per_sample_csv}")


if __name__ == "__main__":
    main()
